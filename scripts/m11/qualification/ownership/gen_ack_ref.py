"""TEST-ONLY: emit ack_ref.inc with VERBATIM pinned-ACK (b97c62c4) kernel code used
as the W3 reference: ctype isspace + _ctype table, skip_spaces, next_arg, parameq.
Each source is SHA-256 checked before extraction; #line directives point back to
the original file/line so diagnostics cite the pinned source.
Usage: python -I gen_ack_ref.py <ack_dir> <out.inc>"""
import hashlib, sys
from pathlib import Path

PINNED = {
    'include_linux_ctype.h': '54f855457c29b2be6533a4a3d2d55ca4e8e6db7cd0a99acb665cc226619f28f3',
    'lib_ctype.c': '1675d7654e76e66979b031d05570f73438f1f3808fca8c6f1d51274181ad2d59',
    'lib_string.c': '92c8024ac584fc4bc0d18052d0b6ef278c5dbf0d6be5e5b94f1671c79b0d984e',
    'lib_cmdline.c': '68d43d194fd14033fa9684c7732ad90b4f150896efde05174858a9db58e00e40',
    'kernel_params.c': '0f1073043e331b1c91cdea7ec08cb8fbcfa753040153ba0148db2a6108b0faa6',
}
# (file, first_line, last_line) inclusive, 1-based; contents asserted below.
RANGES = [
    ('include_linux_ctype.h', 10, 21),   # _U.._SP, extern _ctype[], __ismask
    ('include_linux_ctype.h', 35, 35),   # isspace
    ('lib_ctype.c', 12, 36),             # const unsigned char _ctype[] = {...};
    ('lib_string.c', 525, 530),          # skip_spaces
    ('lib_cmdline.c', 201, 249),         # next_arg
    ('kernel_params.c', 77, 98),         # dash2underscore, parameqn, parameq
]
EXPECT_FIRST = {
    ('include_linux_ctype.h', 10): '#define _U',
    ('include_linux_ctype.h', 35): '#define isspace(c)',
    ('lib_ctype.c', 12): 'const unsigned char _ctype[] = {',
    ('lib_string.c', 525): 'char *skip_spaces(const char *str)',
    ('lib_cmdline.c', 201): 'char *next_arg(char *args, char **param, char **val)',
    ('kernel_params.c', 77): 'static char dash2underscore(char c)',
}
# Last line of each range, and the line before it where that pins a function end.
EXPECT_LAST = {
    ('include_linux_ctype.h', 21): ('#define __ismask(x)', None),
    ('include_linux_ctype.h', 35): ('#define isspace(c)', None),
    ('lib_ctype.c', 36): ('_L,_L,_L,_L,_L,_L,_L,_P,_L,_L,_L,_L,_L,_L,_L,_L};', None),
    ('lib_string.c', 530): ('}', '\treturn (char *)str;'),
    ('lib_cmdline.c', 249): ('}', '\treturn skip_spaces(next);'),
    ('kernel_params.c', 98): ('}', '\treturn parameqn(a, b, strlen(a)+1);'),
}

def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    lines = {}
    for name, digest in PINNED.items():
        raw = (src / name).read_bytes()
        got = hashlib.sha256(raw).hexdigest()
        assert got == digest, f'{name}: sha256 {got} != pinned {digest}'
        lines[name] = raw.decode('utf-8').split('\n')
    parts = ['/* GENERATED by gen_ack_ref.py from pinned ACK b97c62c4 sources. DO NOT EDIT. */']
    for name, a, b in RANGES:
        chunk = lines[name][a - 1:b]
        key = (name, a)
        if key in EXPECT_FIRST:
            assert chunk[0].startswith(EXPECT_FIRST[key]), (name, a, chunk[0])
        last, before = EXPECT_LAST[(name, b)]
        assert chunk[-1].startswith(last), (name, b, chunk[-1])
        if before is not None:
            assert chunk[-2] == before, (name, b - 1, chunk[-2])
        parts.append(f'#line {a} "{name}"')
        parts.extend(chunk)
    body = '\n'.join(parts) + '\n'
    out.write_text(body, encoding='utf-8', newline='\n')
    print(f'wrote {out} sha256={hashlib.sha256(body.encode()).hexdigest()}')

if __name__ == '__main__':
    main()
